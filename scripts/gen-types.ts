/**
 * Generates src/types/database.ts from a Postgres database (no Docker needed).
 * Usage: DATABASE_URL=postgresql://user@localhost:5432/merta_deal pnpm gen:types
 * Output mirrors `supabase gen types typescript` closely enough for supabase-js typing.
 */
import { Client } from "pg";
import { writeFileSync } from "node:fs";

const url = process.env.DATABASE_URL ?? "postgresql://sameer@localhost:5432/merta_deal";

const scalar: Record<string, string> = {
  uuid: "string", text: "string", varchar: "string", bpchar: "string", citext: "string",
  int2: "number", int4: "number", int8: "number", numeric: "number", float4: "number", float8: "number",
  bool: "boolean", timestamptz: "string", timestamp: "string", date: "string", time: "string", timetz: "string",
  json: "Json", jsonb: "Json", bytea: "string", tsvector: "unknown", interval: "string", inet: "string",
};

async function main() {
  const c = new Client({ connectionString: url });
  await c.connect();

  const enums = (await c.query(`
    select t.typname as name, array_to_json(array_agg(e.enumlabel order by e.enumsortorder)) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' group by t.typname order by t.typname`)).rows as { name: string; labels: string[] }[];
  const enumNames = new Set(enums.map((e) => e.name));

  const mapType = (udt: string, dataType: string): string => {
    if (dataType === "ARRAY") {
      const inner = udt.startsWith("_") ? udt.slice(1) : udt;
      return `${mapType(inner, "")}[]`;
    }
    if (enumNames.has(udt)) return `Database["public"]["Enums"]["${udt}"]`;
    return scalar[udt] ?? "unknown";
  };

  const tables = (await c.query(`
    select table_name, table_type from information_schema.tables
    where table_schema = 'public' and table_type in ('BASE TABLE','VIEW') order by table_name`)).rows as { table_name: string; table_type: string }[];

  const cols = (await c.query(`
    select table_name, column_name, udt_name, data_type, is_nullable, column_default, is_identity, is_generated
    from information_schema.columns where table_schema = 'public' order by table_name, ordinal_position`)).rows as {
    table_name: string; column_name: string; udt_name: string; data_type: string; is_nullable: string; column_default: string | null; is_identity: string; is_generated: string;
  }[];

  const fks = (await c.query(`
    select tc.table_name, kcu.column_name, ccu.table_name as ref_table, ccu.column_name as ref_column, tc.constraint_name
    from information_schema.table_constraints tc
    join information_schema.key_column_usage kcu on kcu.constraint_name = tc.constraint_name and kcu.table_schema = tc.table_schema
    join information_schema.constraint_column_usage ccu on ccu.constraint_name = tc.constraint_name and ccu.table_schema = tc.table_schema
    where tc.constraint_type = 'FOREIGN KEY' and tc.table_schema = 'public' order by 1,2`)).rows as { table_name: string; column_name: string; ref_table: string; ref_column: string; constraint_name: string }[];

  const fns = (await c.query(`
    select p.proname as name,
           pg_get_function_arguments(p.oid) as args,
           pg_get_function_result(p.oid) as result,
           p.proretset as retset,
           t.typname as rettype,
           (select array_to_json(array_agg(a.n order by a.i)) from unnest(p.proargnames) with ordinality a(n, i)) as argnames,
           (select array_to_json(array_agg(format_type(a.t, null) order by a.i)) from unnest(p.proargtypes) with ordinality a(t, i)) as argtypes,
           p.pronargdefaults as ndefaults
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type t on t.oid = p.prorettype
    where n.nspname = 'public' and p.prokind = 'f' and p.proname not like '\\_%' order by p.proname`)).rows as {
    name: string; args: string; result: string; retset: boolean; rettype: string; argnames: string[] | null; argtypes: string[] | null; ndefaults: number;
  }[];

  const mapSqlType = (t: string): string => {
    const base = t.replace(/\[\]$/, "");
    const arr = t.endsWith("[]");
    const m: Record<string, string> = {
      uuid: "string", text: "string", integer: "number", bigint: "number", numeric: "number", "double precision": "number", boolean: "boolean",
      jsonb: "Json", json: "Json", "timestamp with time zone": "string", date: "string", smallint: "number", real: "number",
    };
    let out = m[base];
    if (!out) {
      const en = base.replace(/^public\./, "");
      out = enumNames.has(en) ? `Database["public"]["Enums"]["${en}"]` : (tables.some((x) => x.table_name === en) ? `Database["public"]["Tables"]["${en}"]["Row"]` : "unknown");
    }
    return arr ? `${out}[]` : out;
  };

  let out = `// Generated by scripts/gen-types.ts — do not edit by hand.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]\n\nexport type Database = {\n  public: {\n    Tables: {\n`;
  const emitTable = (t: { table_name: string; table_type: string }) => {
    const tc = cols.filter((x) => x.table_name === t.table_name);
    const row = tc.map((x) => `          ${x.column_name}: ${mapType(x.udt_name, x.data_type)}${x.is_nullable === "YES" ? " | null" : ""}`).join("\n");
    const insert = tc.map((x) => {
      const optional = x.is_nullable === "YES" || x.column_default !== null || x.is_identity === "YES" || x.is_generated !== "NEVER";
      return `          ${x.column_name}${optional ? "?" : ""}: ${mapType(x.udt_name, x.data_type)}${x.is_nullable === "YES" ? " | null" : ""}`;
    }).join("\n");
    const update = tc.map((x) => `          ${x.column_name}?: ${mapType(x.udt_name, x.data_type)}${x.is_nullable === "YES" ? " | null" : ""}`).join("\n");
    const rels = fks.filter((f) => f.table_name === t.table_name).map((f) => `          {\n            foreignKeyName: "${f.constraint_name}"\n            columns: ["${f.column_name}"]\n            isOneToOne: false\n            referencedRelation: "${f.ref_table}"\n            referencedColumns: ["${f.ref_column}"]\n          }`).join(",\n");
    return `      ${t.table_name}: {\n        Row: {\n${row}\n        }\n        Insert: {\n${insert}\n        }\n        Update: {\n${update}\n        }\n        Relationships: [\n${rels}\n        ]\n      }\n`;
  };
  for (const t of tables.filter((x) => x.table_type === "BASE TABLE")) out += emitTable(t);
  out += `    }\n    Views: {\n`;
  for (const t of tables.filter((x) => x.table_type === "VIEW")) {
    const tc = cols.filter((x) => x.table_name === t.table_name);
    const row = tc.map((x) => `          ${x.column_name}: ${mapType(x.udt_name, x.data_type)}${x.is_nullable === "YES" ? " | null" : ""}`).join("\n");
    out += `      ${t.table_name}: {\n        Row: {\n${row}\n        }\n        Relationships: []\n      }\n`;
  }
  out += `    }\n    Functions: {\n`;
  const seen = new Set<string>();
  for (const f of fns) {
    if (seen.has(f.name)) continue; seen.add(f.name);
    const names = f.argnames ?? []; const types = f.argtypes ?? [];
    const nreq = types.length - f.ndefaults;
    const args = types.map((t, i) => `          ${names[i] ?? `arg${i}`}${i >= nreq ? "?" : ""}: ${mapSqlType(t)}`).join("\n");
    let ret: string;
    if (f.result.startsWith("TABLE(")) {
      const inner = f.result.slice(6, -1).split(",").map((p) => p.trim()).map((p) => { const i = p.indexOf(" "); return `${p.slice(0, i)}: ${mapSqlType(p.slice(i + 1))}`; });
      ret = `{\n          ${inner.join("\n          ")}\n        }[]`;
    } else if (f.rettype === "void") ret = "undefined";
    else if (f.rettype === "trigger") continue;
    else { ret = mapSqlType(f.rettype.startsWith("_") ? f.rettype.slice(1) + "[]" : f.rettype === "int4" ? "integer" : f.rettype === "int8" ? "bigint" : f.rettype === "bool" ? "boolean" : f.rettype === "float8" ? "double precision" : f.rettype); if (f.retset && !ret.endsWith("[]")) ret += "[]"; }
    out += `      ${f.name}: {\n        Args: ${types.length ? `{\n${args}\n        }` : "Record<PropertyKey, never>"}\n        Returns: ${ret}\n      }\n`;
  }
  out += `    }\n    Enums: {\n`;
  for (const e of enums) out += `      ${e.name}: ${e.labels.map((l) => JSON.stringify(l)).join(" | ")}\n`;
  out += `    }\n    CompositeTypes: Record<string, never>\n  }\n}\n\n`;
  out += `type PublicSchema = Database["public"]\nexport type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"]\nexport type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"]\nexport type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"]\nexport type Views<T extends keyof PublicSchema["Views"]> = PublicSchema["Views"][T]["Row"]\nexport type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T]\nexport type Functions<T extends keyof PublicSchema["Functions"]> = PublicSchema["Functions"][T]\n`;
  writeFileSync("src/types/database.ts", out);
  console.log(`wrote src/types/database.ts: ${tables.length} tables/views, ${seen.size} functions, ${enums.length} enums`);
  await c.end();
}
main().catch((e) => { console.error(e); process.exit(1); });
