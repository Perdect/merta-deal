import type { Metadata } from "next";
import { redirect } from "next/navigation";
import { Wallet, Percent, Info } from "lucide-react";
import { getMyStore, getStoreEarnings, getStorePayouts, getStoreStats } from "@/lib/data/store";
import { PAYOUT_STATUS_META } from "@/components/store/constants";
import { EarningsTabs } from "@/components/store/earnings-tabs";
import { PageHeader } from "@/components/ui/misc";
import { Stat, Card, CardHeader, CardBody } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Alert } from "@/components/ui/states";
import { formatINR, formatDate, formatNumber } from "@/lib/utils";

export const metadata: Metadata = { title: "Earnings" };
export const dynamic = "force-dynamic";

export default async function StoreEarningsPage() {
  const membership = await getMyStore();
  if (!membership) redirect("/store/register");
  const { store } = membership;
  const [earnings, payouts, stats] = await Promise.all([getStoreEarnings(store.id), getStorePayouts(store.id, 50), getStoreStats(store.id)]);
  const effectiveRate = earnings.window_gross > 0 ? (earnings.window_commission / earnings.window_gross) * 100 : null;
  const pendingPayout = payouts.filter((p) => p.status === "pending" || p.status === "processing").reduce((s, p) => s + Number(p.net_amount), 0);

  return (
    <div className="space-y-4">
      <PageHeader title="Earnings" subtitle={`Delivered orders, last ${earnings.window_days} days`} className="px-0" />
      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Stat label="Gross sales" value={formatINR(earnings.window_gross)} hint={`${formatNumber(earnings.window_orders)} delivered orders`} />
        <Stat label="Commission" value={`− ${formatINR(earnings.window_commission)}`} icon={<Percent className="h-4 w-4" />} hint={effectiveRate != null ? `${effectiveRate.toFixed(1)}% effective` : undefined} />
        <Stat label="Net earnings" value={formatINR(earnings.window_net)} tone="brand" icon={<Wallet className="h-4 w-4" />} />
        <Stat label="Lifetime net" value={formatINR(stats?.total_revenue ?? 0)} hint={pendingPayout > 0 ? `${formatINR(pendingPayout)} payout pending` : "All delivered orders"} />
      </div>

      <Alert tone="info" icon={<Info className="h-4 w-4" />} title={store.commission_rate != null ? `Your commission rate: ${Number(store.commission_rate)}%` : "Commission: platform default rate"}>
        {store.commission_rate != null ? "A custom rate set by Merta Deal for your store. " : "No custom rate is set for your store, so the platform-wide default applies (managed by admins). "}
        Each order records the exact rate applied at the time, so historic figures never change. Commission is charged on item value (not on delivery or platform fees).
      </Alert>
      {earnings.capped ? <p className="text-xs text-ink-3">Showing the most recent {formatNumber(earnings.window_orders)} orders in this window.</p> : null}

      <EarningsTabs daily={earnings.daily} weekly={earnings.weekly} />

      <Card>
        <CardHeader title="Payouts" subtitle="Settlements from Merta Deal to your bank / UPI" />
        <CardBody>
          {payouts.length === 0 ? <p className="text-sm text-ink-3">No payouts yet. Payouts are generated by the platform for each settlement period and appear here with their status.</p> : (
            <ul className="divide-y divide-line">
              {payouts.map((p) => {
                const m = PAYOUT_STATUS_META[p.status];
                return (
                  <li key={p.id} className="flex items-center gap-3 py-2.5">
                    <div className="min-w-0 flex-1">
                      <p className="text-sm font-semibold text-ink">{formatDate(p.period_start)} – {formatDate(p.period_end)}</p>
                      <p className="text-xs text-ink-3">{p.order_count} orders · gross {formatINR(p.gross_sales)} · commission {formatINR(p.commission_amount)}{Number(p.adjustments) ? ` · adjustments ${formatINR(p.adjustments)}` : ""}{p.reference_no ? ` · ref ${p.reference_no}` : ""}{p.note ? ` · ${p.note}` : ""}</p>
                    </div>
                    <div className="text-right"><p className="text-sm font-bold tabular text-ink">{formatINR(p.net_amount)}</p><Badge tone={m.tone} size="xs">{m.label}{p.paid_at ? ` · ${formatDate(p.paid_at)}` : ""}</Badge></div>
                  </li>
                );
              })}
            </ul>
          )}
        </CardBody>
      </Card>
    </div>
  );
}
